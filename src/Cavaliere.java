public class Cavaliere {
    private String nome;
    private int puntiVita;
    private String arma;
    private int forzaAttacco;


    public Cavaliere(String nome, int puntiVita, String arma, int forzaAttacco){
        this.nome=nome;
        this.puntiVita=puntiVita;
        this.arma=arma;
        this.forzaAttacco=forzaAttacco;

    }
}
